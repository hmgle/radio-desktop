// Command gencountrynames extracts Chinese CLDR region names so the desktop
// binary does not need the full language/display dictionaries at runtime.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"

	"golang.org/x/text/language/display"
)

func main() {
	out := flag.String("out", "country_names_gen.go", "output Go file")
	flag.Parse()

	names := display.SimplifiedChinese.Regions()
	labels := make(map[string]string)
	var codes []string
	for _, region := range display.Values.Regions() {
		code := region.String()
		if name := names.Name(region); len(code) == 2 && code != "ZZ" && name != "" {
			labels[code] = name
			codes = append(codes, code)
		}
	}
	slices.Sort(codes)

	var source bytes.Buffer
	fmt.Fprintln(&source, "// Code generated by go generate ./internal/store; DO NOT EDIT.")
	fmt.Fprintln(&source, "// Source: golang.org/x/text/language/display (version pinned in go.mod).")
	fmt.Fprintln(&source, "\npackage store")
	fmt.Fprintln(&source, "\n// Prefix matching and display share one set of Chinese CLDR names.")
	fmt.Fprintln(&source, "var chineseCountryNames = map[string]string{")
	for _, code := range codes {
		fmt.Fprintf(&source, "\t%q: %q,\n", code, labels[code])
	}
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
